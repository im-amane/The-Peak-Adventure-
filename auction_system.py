"""Transactional player auction house for equipped weapons and armor."""
import time

class AuctionError(ValueError):
    pass

DEFAULTS = {"weapon": ("Rusty Sword", 0), "armor": ("Traveler Clothes", 0)}


def _timestamp(value):
    if value is None:
        return int(time.time())
    if type(value) is not int or value < 0:
        raise AuctionError("Invalid auction timestamp.")
    return value


def _positive_id(value, label):
    if type(value) is not int or value <= 0:
        raise AuctionError(f"Invalid {label} account or ID.")
    return value


def _is_postgres(db):
    return getattr(db, "dialect", "sqlite") == "postgres"


def _for_update(db, sql):
    """Serialize auction mutations on PostgreSQL; SQLite already serializes writers."""
    return f"{sql} FOR UPDATE" if _is_postgres(db) else sql


async def _table_exists(db, table):
    if _is_postgres(db):
        cur = await db.execute(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema=current_schema() AND table_name=? AND table_type='BASE TABLE'",
            (table,),
        )
    else:
        cur = await db.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?",
            (table,),
        )
    if await cur.fetchone():
        return True
    if await _table_exists(db, "matchmaking_queue"):
        cur = await db.execute(
            "SELECT 1 FROM matchmaking_queue WHERE user_id=? AND status IN ('queued','matched') LIMIT 1",
            (user_id,),
        )
        if await cur.fetchone():
            return True
    return False


async def init_auction_tables(db):
    nested = db.in_transaction
    savepoint = "init_auction_tables"
    if nested:
        await db.execute(f"SAVEPOINT {savepoint}")
    else:
        await db.execute("BEGIN IMMEDIATE")
    identity = (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if _is_postgres(db)
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    user_id_type = "BIGINT" if _is_postgres(db) else "INTEGER"
    try:
        await db.execute(f"""CREATE TABLE IF NOT EXISTS auction_listings (
          listing_id {identity},
          seller_id {user_id_type} NOT NULL,
          slot TEXT NOT NULL CHECK(slot IN ('weapon','armor')),
          item_name TEXT NOT NULL,
          item_stat INTEGER NOT NULL CHECK(item_stat >= 0),
          start_price INTEGER NOT NULL CHECK(start_price > 0),
          current_bid INTEGER NOT NULL DEFAULT 0,
          highest_bidder {user_id_type},
          ends_at INTEGER NOT NULL,
          status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','sold','expired','cancelled')),
          created_at INTEGER NOT NULL
        )""")
        await db.execute("CREATE INDEX IF NOT EXISTS idx_auction_active ON auction_listings(status, ends_at)")
        await db.execute("CREATE INDEX IF NOT EXISTS idx_auction_seller ON auction_listings(seller_id, status)")
        await db.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS idx_auction_one_active_seller "
            "ON auction_listings(seller_id) WHERE status='active'"
        )
        await db.execute(f"""CREATE TABLE IF NOT EXISTS auction_stash(
          stash_id {identity},user_id {user_id_type} NOT NULL,
          slot TEXT NOT NULL CHECK(slot IN ('weapon','armor')),item_name TEXT NOT NULL,
          item_stat INTEGER NOT NULL,source_listing_id {user_id_type},created_at INTEGER NOT NULL
        )""")
        await db.execute("CREATE INDEX IF NOT EXISTS idx_auction_stash_user ON auction_stash(user_id,stash_id)")
        if nested:
            await db.execute(f"RELEASE SAVEPOINT {savepoint}")
        else:
            await db.commit()
    except Exception:
        if nested:
            await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
            await db.execute(f"RELEASE SAVEPOINT {savepoint}")
        else:
            await db.rollback()
        raise

async def _has_active_battle(db, user_id):
    if not await _table_exists(db, "battles"):
        return False
    cur = await db.execute("SELECT 1 FROM battles WHERE user_id=?", (user_id,))
    return await cur.fetchone() is not None

async def _lock_player_for_equipment(db, user_id):
    """Coordinate auction equipment changes with gameplay and matchmaking locks."""
    if _is_postgres(db):
        await db.execute("SELECT pg_advisory_xact_lock(?)", (user_id,))
        await db.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
            (f"peak-adventure-matchmaking-player:{user_id}",),
        )


async def _has_active_player_activity(db, user_id):
    if await _table_exists(db, "duels"):
        cur = await db.execute(
            "SELECT 1 FROM duels WHERE status IN ('pending','active') "
            "AND (challenger_id=? OR opponent_id=?) LIMIT 1",
            (user_id, user_id),
        )
        if await cur.fetchone():
            return True
    if await _table_exists(db, "trades"):
        cur = await db.execute(
            "SELECT 1 FROM trades WHERE status IN ('pending','open') "
            "AND (initiator_id=? OR partner_id=?) LIMIT 1",
            (user_id, user_id),
        )
        if await cur.fetchone():
            return True
    if await _table_exists(db, "matchmaking_queue"):
        cur = await db.execute(
            "SELECT 1 FROM matchmaking_queue WHERE user_id=? AND status IN ('queued','matched') LIMIT 1",
            (user_id,),
        )
        if await cur.fetchone():
            return True
    return False


async def _return_listing_item(db, seller_id, slot, item_name, item_stat, listing_id, now):
    """Return escrowed gear without overwriting equipment acquired during listing."""
    stat_column = "weapon_attack" if slot == "weapon" else "armor_defense"
    cur = await db.execute(
        _for_update(db, f"SELECT {slot},{stat_column} FROM players WHERE user_id=?"),
        (seller_id,),
    )
    equipped = await cur.fetchone()
    if not equipped:
        return False
    current_name, current_stat = equipped[slot], equipped[stat_column]
    if await _has_active_battle(db, seller_id) or await _has_active_player_activity(db, seller_id):
        await db.execute(
            """INSERT INTO auction_stash
               (user_id,slot,item_name,item_stat,source_listing_id,created_at)
               VALUES(?,?,?,?,?,?)""",
            (seller_id, slot, item_name, item_stat, listing_id, now),
        )
        return True
    if (current_name, current_stat) != DEFAULTS[slot]:
        await db.execute(
            """INSERT INTO auction_stash
               (user_id,slot,item_name,item_stat,source_listing_id,created_at)
               VALUES(?,?,?,?,?,?)""",
            (seller_id, slot, current_name, current_stat, listing_id, now),
        )
    await db.execute(
        f"UPDATE players SET {slot}=?,{stat_column}=? WHERE user_id=?",
        (item_name, item_stat, seller_id),
    )
    return True


async def _settle_due(db, now):
    nested = db.in_transaction
    savepoint = "auction_expiry_settlement"
    if nested:
        await db.execute(f"SAVEPOINT {savepoint}")
    else:
        await db.execute("BEGIN IMMEDIATE")
    try:
        cur = await db.execute(
            _for_update(
                db,
                "SELECT * FROM auction_listings WHERE status='active' AND ends_at<=?",
            ),
            (now,),
        )
        rows = await cur.fetchall()
        affected_players = {
            player_id
            for row in rows
            for player_id in (row["seller_id"], row["highest_bidder"])
            if player_id is not None
        }
        for player_id in sorted(affected_players):
            await _lock_player_for_equipment(db, player_id)
        for row in rows:
            if row["highest_bidder"] is not None:
                seller = await db.execute(
                    "SELECT 1 FROM players WHERE user_id=?",
                    (row["seller_id"],),
                )
                buyer = await db.execute(
                    "SELECT 1 FROM players WHERE user_id=?",
                    (row["highest_bidder"],),
                )
                seller_exists = await seller.fetchone() is not None
                buyer_exists = await buyer.fetchone() is not None
                if seller_exists and buyer_exists:
                    await db.execute(
                        "UPDATE players SET coins=coins+? WHERE user_id=?",
                        (row["current_bid"], row["seller_id"]),
                    )
                    column = row["slot"]
                    stat_column = "weapon_attack" if column == "weapon" else "armor_defense"
                    current = await db.execute(
                        _for_update(
                        db, f"SELECT {column}, {stat_column} FROM players WHERE user_id=?"
                    ),
                        (row["highest_bidder"],),
                    )
                    equipped = await current.fetchone()
                    if await _has_active_battle(db, row["highest_bidder"]) or await _has_active_player_activity(db, row["highest_bidder"]):
                        await db.execute(
                            """INSERT INTO auction_stash
                               (user_id,slot,item_name,item_stat,source_listing_id,created_at)
                               VALUES(?,?,?,?,?,?)""",
                            (row["highest_bidder"], column, row["item_name"],
                             row["item_stat"], row["listing_id"], now),
                        )
                    else:
                        if equipped:
                            await db.execute(
                                """INSERT INTO auction_stash
                                   (user_id,slot,item_name,item_stat,source_listing_id,created_at)
                                   VALUES(?,?,?,?,?,?)""",
                                (row["highest_bidder"], column, equipped[column],
                                 equipped[stat_column], row["listing_id"], now),
                            )
                        await db.execute(
                            f"UPDATE players SET {column}=?, {stat_column}=? WHERE user_id=?",
                            (row["item_name"], row["item_stat"], row["highest_bidder"]),
                        )
                    await db.execute(
                        "UPDATE auction_listings SET status='sold' WHERE listing_id=? AND status='active'",
                        (row["listing_id"],),
                    )
                else:
                    # Never pay a seller when the escrow owner account no longer
                    # exists. Refund only when the bidder can still receive it.
                    if buyer_exists:
                        await db.execute(
                            "UPDATE players SET coins=coins+? WHERE user_id=?",
                            (row["current_bid"], row["highest_bidder"]),
                        )
                    if seller_exists:
                        await _return_listing_item(
                            db, row["seller_id"], row["slot"], row["item_name"],
                            row["item_stat"], row["listing_id"], now,
                        )
                    await db.execute(
                        "UPDATE auction_listings SET status='expired' WHERE listing_id=? AND status='active'",
                        (row["listing_id"],),
                    )
            else:
                await _return_listing_item(
                    db, row["seller_id"], row["slot"], row["item_name"],
                    row["item_stat"], row["listing_id"], now,
                )
                await db.execute(
                    "UPDATE auction_listings SET status='expired' WHERE listing_id=? AND status='active'",
                    (row["listing_id"],),
                )
        if nested:
            await db.execute(f"RELEASE SAVEPOINT {savepoint}")
        else:
            await db.commit()
    except Exception:
        if nested:
            await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
            await db.execute(f"RELEASE SAVEPOINT {savepoint}")
        else:
            await db.rollback()
        raise

async def create_listing(db, seller_id, slot, start_price, duration_hours=24, now=None):
    now = _timestamp(now)
    _positive_id(seller_id, "seller")
    if not isinstance(slot, str) or slot not in DEFAULTS:
        raise AuctionError("Only equipped weapons and armor can be listed.")
    if type(start_price) is not int or not 1 <= start_price <= 10_000_000:
        raise AuctionError("Starting bid must be between 1 and 10,000,000 coins.")
    if type(duration_hours) is not int or not 1 <= duration_hours <= 168:
        raise AuctionError("Auction duration must be between 1 and 168 hours.")
    await _settle_due(db, now)
    try:
        await db.execute("BEGIN IMMEDIATE")
        await _lock_player_for_equipment(db, seller_id)
        cur = await db.execute(
            _for_update(db, "SELECT * FROM players WHERE user_id=?"),
            (seller_id,),
        )
        player = await cur.fetchone()
        if not player:
            raise AuctionError("Register before using the auction house.")
        if await _has_active_battle(db, seller_id):
            raise AuctionError("Finish your active battle before listing equipped gear.")
        if await _has_active_player_activity(db, seller_id):
            raise AuctionError("Finish your active duel or trade before listing equipped gear.")
        cur = await db.execute("SELECT 1 FROM auction_listings WHERE seller_id=? AND status='active'", (seller_id,))
        if await cur.fetchone():
            raise AuctionError("You already have an active auction.")
        item_name, item_stat = player[slot], player["weapon_attack" if slot == "weapon" else "armor_defense"]
        if item_name == DEFAULTS[slot][0] and item_stat == 0:
            raise AuctionError("Your starter equipment cannot be auctioned.")
        column = slot
        stat_column = "weapon_attack" if slot == "weapon" else "armor_defense"
        await db.execute(f"UPDATE players SET {column}=?, {stat_column}=? WHERE user_id=?", (*DEFAULTS[slot], seller_id))
        insert_sql = (
            """INSERT INTO auction_listings
               (seller_id,slot,item_name,item_stat,start_price,ends_at,created_at)
               VALUES(?,?,?,?,?,?,?) RETURNING listing_id"""
            if _is_postgres(db)
            else """INSERT INTO auction_listings
               (seller_id,slot,item_name,item_stat,start_price,ends_at,created_at)
               VALUES(?,?,?,?,?,?,?)"""
        )
        cur = await db.execute(
            insert_sql,
            (seller_id,slot,item_name,item_stat,start_price,now+duration_hours*3600,now),
        )
        listing_id = (await cur.fetchone())["listing_id"] if _is_postgres(db) else cur.lastrowid
        await db.commit()
        return listing_id
    except Exception:
        await db.rollback()
        raise

async def place_bid(db, bidder_id, listing_id, amount, now=None):
    now = _timestamp(now)
    _positive_id(bidder_id, "bidder")
    _positive_id(listing_id, "auction")
    if type(amount) is not int or not 1 <= amount <= 10_000_000:
        raise AuctionError("Bid must be between 1 and 10,000,000 coins.")
    await _settle_due(db, now)
    try:
        await db.execute("BEGIN IMMEDIATE")
        cur = await db.execute(
            _for_update(
                db,
                "SELECT * FROM auction_listings WHERE listing_id=? AND status='active'",
            ),
            (listing_id,),
        )
        listing = await cur.fetchone()
        if not listing or listing["ends_at"] <= now:
            raise AuctionError("This auction is no longer active.")
        if bidder_id == listing["seller_id"]:
            raise AuctionError("You cannot bid on your own item.")
        minimum = max(listing["start_price"], listing["current_bid"] + max(1, listing["current_bid"] // 20))
        if amount < minimum:
            raise AuctionError(f"Minimum next bid is {minimum} coins.")
        cur = await db.execute("UPDATE players SET coins=coins-? WHERE user_id=? AND coins>=?", (amount,bidder_id,amount))
        if cur.rowcount != 1:
            raise AuctionError("Insufficient coins or player account not found.")
        if listing["highest_bidder"] is not None:
            await db.execute("UPDATE players SET coins=coins+? WHERE user_id=?", (listing["current_bid"],listing["highest_bidder"]))
        await db.execute("UPDATE auction_listings SET current_bid=?,highest_bidder=? WHERE listing_id=?", (amount,bidder_id,listing_id))
        await db.commit()
        return minimum, amount
    except Exception:
        await db.rollback()
        raise

async def cancel_listing(db, seller_id, listing_id, now=None):
    _positive_id(seller_id, "seller")
    _positive_id(listing_id, "auction")
    now = _timestamp(now)
    await _settle_due(db, now)
    try:
        await db.execute("BEGIN IMMEDIATE")
        cur = await db.execute(
            _for_update(
                db,
                "SELECT * FROM auction_listings WHERE listing_id=? AND status='active'",
            ),
            (listing_id,),
        )
        row = await cur.fetchone()
        if not row or row["seller_id"] != seller_id:
            raise AuctionError("Active auction not found for your account.")
        if row["highest_bidder"] is not None:
            raise AuctionError("An auction with bids cannot be cancelled.")
        await _return_listing_item(
            db, seller_id, row["slot"], row["item_name"], row["item_stat"],
            row["listing_id"], now,
        )
        await db.execute("UPDATE auction_listings SET status='cancelled' WHERE listing_id=?", (listing_id,))
        await db.commit()
    except Exception:
        await db.rollback()
        raise

async def list_active_auctions(db, now=None, limit=20):
    now = _timestamp(now)
    if type(limit) is not int or limit < 1:
        raise AuctionError("Auction list limit must be a positive integer.")
    await _settle_due(db, now)
    cur = await db.execute("""SELECT listing_id,seller_id,slot,item_name,item_stat,start_price,current_bid,
      highest_bidder,ends_at FROM auction_listings WHERE status='active' AND ends_at>?
      ORDER BY ends_at ASC,listing_id ASC LIMIT ?""", (now,max(1,min(int(limit),50))))
    return await cur.fetchall()

async def get_auction(db, listing_id, now=None):
    _positive_id(listing_id, "auction")
    rows = await list_active_auctions(db, now, 50)
    return next((row for row in rows if row["listing_id"] == listing_id), None)

async def list_stash(db, user_id):
    _positive_id(user_id, "player")
    cur = await db.execute("SELECT stash_id,slot,item_name,item_stat,created_at FROM auction_stash WHERE user_id=? ORDER BY stash_id", (user_id,))
    return await cur.fetchall()

async def equip_stashed_item(db, user_id, stash_id):
    _positive_id(user_id, "player")
    _positive_id(stash_id, "stash")
    try:
        await db.execute("BEGIN IMMEDIATE")
        await _lock_player_for_equipment(db, user_id)
        cur = await db.execute(
            _for_update(
                db, "SELECT * FROM auction_stash WHERE stash_id=? AND user_id=?"
            ),
            (stash_id,user_id),
        )
        item = await cur.fetchone()
        if not item:
            raise AuctionError("That stored item does not belong to your account.")
        if await _has_active_battle(db, user_id):
            raise AuctionError("Finish your active battle before changing equipment.")
        if await _has_active_player_activity(db, user_id):
            raise AuctionError("Finish your active duel or trade before changing equipment.")
        slot = item["slot"]
        stat_column = "weapon_attack" if slot == "weapon" else "armor_defense"
        cur = await db.execute(
            _for_update(
                db, f"SELECT {slot},{stat_column} FROM players WHERE user_id=?"
            ),
            (user_id,),
        )
        player = await cur.fetchone()
        if not player:
            raise AuctionError("Player account not found.")
        await db.execute("INSERT INTO auction_stash(user_id,slot,item_name,item_stat,source_listing_id,created_at) VALUES(?,?,?,?,?,?)",
          (user_id,slot,player[slot],player[stat_column],None,int(time.time())))
        await db.execute(f"UPDATE players SET {slot}=?,{stat_column}=? WHERE user_id=?", (item["item_name"],item["item_stat"],user_id))
        await db.execute("DELETE FROM auction_stash WHERE stash_id=?", (stash_id,))
        await db.commit()
        return item["item_name"],slot,item["item_stat"]
    except Exception:
        await db.rollback()
        raise
