"""Server-authoritative 1v1 matchmaking queue with bounded rating/level expansion."""
from __future__ import annotations

import time
from functools import wraps
from typing import Any


MATCHMAKING_MODES = {"casual", "ranked"}
MAX_QUEUE_WAIT_SECONDS = 180
JOIN_COOLDOWN_SECONDS = 10
BASE_RATING_WINDOW = 150
MAX_RATING_WINDOW = 600
RATING_WINDOW_STEP = 50
RATING_WINDOW_INTERVAL = 15
BASE_LEVEL_GAP = 3
MAX_LEVEL_GAP = 15
LEVEL_GAP_INTERVAL = 30


class MatchmakingError(ValueError):
    """A matchmaking request cannot be completed."""


def _is_postgres(db: Any) -> bool:
    return getattr(db, "dialect", "sqlite") == "postgres"


def _valid_id(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def _valid_time(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value >= 0


def _now(value: int | None) -> int:
    if value is None:
        return int(time.time())
    if not _valid_time(value):
        raise MatchmakingError("Invalid matchmaking timestamp.")
    return value


async def _begin_atomic(db: Any, savepoint: str) -> bool:
    nested = db.in_transaction
    if nested:
        await db.execute(f"SAVEPOINT {savepoint}")
    else:
        await db.execute("BEGIN IMMEDIATE")
    return nested


async def _commit_atomic(db: Any, nested: bool, savepoint: str) -> None:
    if nested:
        await db.execute(f"RELEASE SAVEPOINT {savepoint}")
    else:
        await db.commit()


async def _rollback_atomic(db: Any, nested: bool, savepoint: str) -> None:
    if nested:
        await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
        await db.execute(f"RELEASE SAVEPOINT {savepoint}")
    else:
        await db.rollback()


def _transactional(function):
    @wraps(function)
    async def wrapped(db, *args, **kwargs):
        savepoint = "matchmaking_" + function.__name__
        nested = await _begin_atomic(db, savepoint)
        try:
            result = await function(db, *args, **kwargs)
            await _commit_atomic(db, nested, savepoint)
            return result
        except Exception:
            await _rollback_atomic(db, nested, savepoint)
            raise
    return wrapped


async def _lock_player(db: Any, user_id: int) -> None:
    """Serialize joins by account, even when requests target different modes."""
    if _is_postgres(db):
        await db.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
            (f"peak-adventure-matchmaking-player:{user_id}",),
        )


async def _lock_mode(db: Any, mode: str) -> None:
    if _is_postgres(db):
        await db.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
            ("peak-adventure-matchmaking:" + mode,),
        )


async def init_matchmaking_tables(db: Any) -> None:
    """Create matchmaking tables and indexes on SQLite or PostgreSQL."""
    identity = (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if _is_postgres(db)
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    statements = (
        f"""CREATE TABLE IF NOT EXISTS matchmaking_matches(
          match_id {identity},
          mode TEXT NOT NULL CHECK(mode IN ('casual','ranked')),
          player_one_id BIGINT NOT NULL REFERENCES players(user_id),
          player_two_id BIGINT NOT NULL REFERENCES players(user_id),
          player_one_level INTEGER NOT NULL,
          player_two_level INTEGER NOT NULL,
          rating_gap INTEGER NOT NULL,
          status TEXT NOT NULL DEFAULT 'matched'
            CHECK(status IN ('matched','completed','cancelled')),
          created_at BIGINT NOT NULL,
          completed_at BIGINT,
          winner_id BIGINT,
          CHECK(player_one_id <> player_two_id)
        )""",
        """CREATE TABLE IF NOT EXISTS matchmaking_queue(
          user_id BIGINT PRIMARY KEY REFERENCES players(user_id),
          mode TEXT NOT NULL CHECK(mode IN ('casual','ranked')),
          player_level INTEGER NOT NULL,
          rating INTEGER NOT NULL,
          status TEXT NOT NULL CHECK(status IN ('queued','matched','cancelled','expired','completed')),
          queued_at BIGINT NOT NULL,
          updated_at BIGINT NOT NULL,
          match_id BIGINT REFERENCES matchmaking_matches(match_id)
        )""",
        """CREATE TABLE IF NOT EXISTS matchmaking_rate_limits(
          user_id BIGINT PRIMARY KEY REFERENCES players(user_id),
          last_joined_at BIGINT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS matchmaking_battles(
          match_id BIGINT PRIMARY KEY REFERENCES matchmaking_matches(match_id),
          player_one_hp INTEGER NOT NULL,
          player_one_max_hp INTEGER NOT NULL,
          player_two_hp INTEGER NOT NULL,
          player_two_max_hp INTEGER NOT NULL,
          turn_user_id BIGINT,
          turn_count INTEGER NOT NULL DEFAULT 0,
          status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','finished')),
          winner_id BIGINT,
          updated_at BIGINT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS matchmaking_battle_stats(
          match_id BIGINT NOT NULL REFERENCES matchmaking_matches(match_id),
          user_id BIGINT NOT NULL REFERENCES players(user_id),
          player_level INTEGER NOT NULL,
          hero_class TEXT NOT NULL,
          weapon_attack INTEGER NOT NULL DEFAULT 0,
          armor_defense INTEGER NOT NULL DEFAULT 0,
          PRIMARY KEY(match_id,user_id)
        )""",
        "CREATE INDEX IF NOT EXISTS idx_matchmaking_queue_search ON matchmaking_queue(mode,status,queued_at)",
        "CREATE INDEX IF NOT EXISTS idx_matchmaking_queue_rating ON matchmaking_queue(mode,status,rating,player_level)",
        "CREATE INDEX IF NOT EXISTS idx_matchmaking_matches_players ON matchmaking_matches(player_one_id,player_two_id,status)",
        """INSERT INTO matchmaking_battles(
             match_id,player_one_hp,player_one_max_hp,player_two_hp,player_two_max_hp,
             turn_user_id,updated_at
           )
           SELECT m.match_id,p1.max_hp,p1.max_hp,p2.max_hp,p2.max_hp,m.player_one_id,m.created_at
           FROM matchmaking_matches m
           JOIN players p1 ON p1.user_id=m.player_one_id
           JOIN players p2 ON p2.user_id=m.player_two_id
           WHERE m.status='matched'
           ON CONFLICT(match_id) DO NOTHING""",
        """INSERT INTO matchmaking_battle_stats(
             match_id,user_id,player_level,hero_class,weapon_attack,armor_defense
           )
           SELECT m.match_id,p.user_id,p.level,p.hero_class,
                  COALESCE(p.weapon_attack,0),COALESCE(p.armor_defense,0)
           FROM matchmaking_matches m
           JOIN players p ON p.user_id=m.player_one_id
           WHERE m.status='matched'
           ON CONFLICT(match_id,user_id) DO NOTHING""",
        """INSERT INTO matchmaking_battle_stats(
             match_id,user_id,player_level,hero_class,weapon_attack,armor_defense
           )
           SELECT m.match_id,p.user_id,p.level,p.hero_class,
                  COALESCE(p.weapon_attack,0),COALESCE(p.armor_defense,0)
           FROM matchmaking_matches m
           JOIN players p ON p.user_id=m.player_two_id
           WHERE m.status='matched'
           ON CONFLICT(match_id,user_id) DO NOTHING""",
    )
    nested = await _begin_atomic(db, "matchmaking_init")
    try:
        for statement in statements:
            await db.execute(statement)
        await _commit_atomic(db, nested, "matchmaking_init")
    except Exception:
        await _rollback_atomic(db, nested, "matchmaking_init")
        raise


def _player_rating(player: Any) -> int:
    wins = max(0, int(player["pvp_wins"] or 0))
    losses = max(0, int(player["pvp_losses"] or 0))
    return max(100, min(3000, 1000 + wins * 20 - losses * 15))


def _allowed_rating_gap(queued_at: int, now: int) -> int:
    waited = max(0, now - queued_at)
    return min(MAX_RATING_WINDOW, BASE_RATING_WINDOW + (waited // RATING_WINDOW_INTERVAL) * RATING_WINDOW_STEP)


def _allowed_level_gap(queued_at: int, now: int) -> int:
    waited = max(0, now - queued_at)
    return min(MAX_LEVEL_GAP, BASE_LEVEL_GAP + waited // LEVEL_GAP_INTERVAL)


async def _queue_payload(db: Any, row: Any) -> dict[str, Any]:
    result = {
        "status": row["status"],
        "mode": row["mode"],
        "player_level": row["player_level"],
        "rating": row["rating"],
        "queued_at": row["queued_at"],
        "updated_at": row["updated_at"],
        "match_id": row["match_id"],
    }
    if row["status"] == "matched" and row["match_id"] is not None:
        cursor = await db.execute(
            """SELECT player_one_id,player_two_id,player_one_level,player_two_level,
                      rating_gap,created_at
               FROM matchmaking_matches WHERE match_id=?""",
            (row["match_id"],),
        )
        match = await cursor.fetchone()
        if match:
            if match["player_one_id"] == row["user_id"]:
                result["opponent_id"] = match["player_two_id"]
                result["opponent_level"] = match["player_two_level"]
            else:
                result["opponent_id"] = match["player_one_id"]
                result["opponent_level"] = match["player_one_level"]
            result["rating_gap"] = match["rating_gap"]
            result["matched_at"] = match["created_at"]
    return result


@_transactional
async def join_matchmaking(
    db: Any,
    user_id: int,
    mode: str = "casual",
    *,
    now: int | None = None,
) -> dict[str, Any]:
    if not _valid_id(user_id):
        raise MatchmakingError("Invalid player account.")
    if not isinstance(mode, str) or mode not in MATCHMAKING_MODES:
        raise MatchmakingError("Choose casual or ranked matchmaking.")
    stamp = _now(now)
    await _lock_player(db, user_id)
    await _lock_mode(db, mode)
    await db.execute(
        """UPDATE matchmaking_queue SET status='expired',updated_at=?
           WHERE user_id=? AND status='queued' AND queued_at<=?""",
        (stamp, user_id, stamp - MAX_QUEUE_WAIT_SECONDS),
    )

    cursor = await db.execute(
        "SELECT level,pvp_wins,pvp_losses FROM players WHERE user_id=?",
        (user_id,),
    )
    battle = await db.execute("SELECT 1 FROM battles WHERE user_id=? LIMIT 1", (user_id,))
    if await battle.fetchone():
        raise MatchmakingError("Finish your active PvE battle before joining matchmaking.")
    duel = await db.execute(
        "SELECT 1 FROM duels WHERE status IN ('pending','active') AND (challenger_id=? OR opponent_id=?) LIMIT 1",
        (user_id, user_id),
    )
    if await duel.fetchone():
        raise MatchmakingError("Finish or decline your active duel before joining matchmaking.")
    trade = await db.execute(
        "SELECT 1 FROM trades WHERE status IN ('pending','open') AND (initiator_id=? OR partner_id=?) LIMIT 1",
        (user_id, user_id),
    )
    if await trade.fetchone():
        raise MatchmakingError("Finish or cancel your active trade before joining matchmaking.")

    player = await cursor.fetchone()
    if not player:
        raise MatchmakingError("Create your hero before joining matchmaking.")
    level = max(1, min(100, int(player["level"] or 1)))
    rating = _player_rating(player)

    cursor = await db.execute(
        "SELECT user_id,mode,player_level,rating,status,queued_at,updated_at,match_id "
        "FROM matchmaking_queue WHERE user_id=?",
        (user_id,),
    )
    existing = await cursor.fetchone()
    if existing and existing["status"] in {"queued", "matched"}:
        if existing["mode"] != mode:
            raise MatchmakingError("Leave your current matchmaking queue first.")
        return await _queue_payload(db, existing)

    cursor = await db.execute(
        "SELECT last_joined_at FROM matchmaking_rate_limits WHERE user_id=?",
        (user_id,),
    )
    rate_limit = await cursor.fetchone()
    if rate_limit and stamp - rate_limit["last_joined_at"] < JOIN_COOLDOWN_SECONDS:
        remaining = JOIN_COOLDOWN_SECONDS - (stamp - rate_limit["last_joined_at"])
        raise MatchmakingError(f"Wait {remaining} seconds before joining matchmaking again.")

    await db.execute(
        """UPDATE matchmaking_queue SET status='expired',updated_at=?
           WHERE mode=? AND status='queued' AND queued_at<=?""",
        (stamp, mode, stamp - MAX_QUEUE_WAIT_SECONDS),
    )

    cursor = await db.execute(
        """SELECT user_id,player_level,rating,queued_at
           FROM matchmaking_queue
           WHERE mode=? AND status='queued' AND user_id<>? AND queued_at>=?
           ORDER BY queued_at,user_id LIMIT 100"""
        + (" FOR UPDATE" if _is_postgres(db) else ""),
        (mode, user_id, stamp - MAX_QUEUE_WAIT_SECONDS),
    )
    candidates = await cursor.fetchall()
    compatible = []
    for candidate in candidates:
        rating_gap = abs(rating - candidate["rating"])
        level_gap = abs(level - candidate["player_level"])
        if (
            rating_gap <= _allowed_rating_gap(candidate["queued_at"], stamp)
            and level_gap <= _allowed_level_gap(candidate["queued_at"], stamp)
        ):
            compatible.append(
                (
                    rating_gap,
                    level_gap,
                    candidate["queued_at"],
                    candidate["user_id"],
                    candidate,
                )
            )

    if compatible:
        _, _, _, _, opponent = min(compatible, key=lambda item: item[:4])
        insert_sql = (
            """INSERT INTO matchmaking_matches(
                 mode,player_one_id,player_two_id,player_one_level,player_two_level,
                 rating_gap,created_at
               ) VALUES(?,?,?,?,?,?,?) RETURNING match_id"""
            if _is_postgres(db)
            else """INSERT INTO matchmaking_matches(
                 mode,player_one_id,player_two_id,player_one_level,player_two_level,
                 rating_gap,created_at
               ) VALUES(?,?,?,?,?,?,?)"""
        )
        cursor = await db.execute(
            insert_sql,
            (
                mode,
                opponent["user_id"],
                user_id,
                opponent["player_level"],
                level,
                abs(opponent["rating"] - rating),
                stamp,
            ),
        )
        match_id = (
            int((await cursor.fetchone())["match_id"])
            if _is_postgres(db)
            else int(cursor.lastrowid)
        )
        cursor = await db.execute(
            """UPDATE matchmaking_queue
               SET status='matched',match_id=?,updated_at=?
               WHERE user_id=? AND status='queued'""",
            (match_id, stamp, opponent["user_id"]),
        )
        if cursor.rowcount != 1:
            raise MatchmakingError("The opponent left the queue. Please try again.")
        await db.execute(
            """INSERT INTO matchmaking_queue(
                 user_id,mode,player_level,rating,status,queued_at,updated_at,match_id
               ) VALUES(?,?,?,?, 'matched',?,?,?)
               ON CONFLICT(user_id) DO UPDATE SET
                 mode=excluded.mode,player_level=excluded.player_level,
                 rating=excluded.rating,status=excluded.status,
                 queued_at=excluded.queued_at,updated_at=excluded.updated_at,
                 match_id=excluded.match_id""",
            (user_id, mode, level, rating, stamp, stamp, match_id),
        )
        player_query = (
            "SELECT user_id,max_hp,level,hero_class,weapon_attack,armor_defense "
            "FROM players WHERE user_id IN (?,?) ORDER BY user_id"
        )
        if _is_postgres(db):
            player_query += " FOR UPDATE"
        player_cursor = await db.execute(player_query, (opponent["user_id"], user_id))
        player_rows = await player_cursor.fetchall()
        player_by_user = {row["user_id"]: row for row in player_rows}
        if opponent["user_id"] not in player_by_user or user_id not in player_by_user:
            raise MatchmakingError("A matched player's combat stats could not be loaded.")
        hp_by_user = {
            player_id: max(1, int(player["max_hp"] or 1))
            for player_id, player in player_by_user.items()
        }
        await db.executemany(
            """INSERT INTO matchmaking_battle_stats(
                 match_id,user_id,player_level,hero_class,weapon_attack,armor_defense
               ) VALUES(?,?,?,?,?,?)""",
            (
                (
                    match_id, player_id, int(player["level"]),
                    player["hero_class"] or "Knight",
                    int(player["weapon_attack"] or 0),
                    int(player["armor_defense"] or 0),
                )
                for player_id, player in player_by_user.items()
            ),
        )
        await db.execute(
            """INSERT INTO matchmaking_battles(
                 match_id,player_one_hp,player_one_max_hp,player_two_hp,player_two_max_hp,
                 turn_user_id,updated_at
               ) VALUES(?,?,?,?,?,?,?)""",
            (
                match_id, hp_by_user[opponent["user_id"]], hp_by_user[opponent["user_id"]],
                hp_by_user[user_id], hp_by_user[user_id], opponent["user_id"], stamp,
            ),
        )
    else:
        match_id = None
        await db.execute(
            """INSERT INTO matchmaking_queue(
                 user_id,mode,player_level,rating,status,queued_at,updated_at,match_id
               ) VALUES(?,?,?,?,'queued',?,?,NULL)
               ON CONFLICT(user_id) DO UPDATE SET
                 mode=excluded.mode,player_level=excluded.player_level,
                 rating=excluded.rating,status='queued',
                 queued_at=excluded.queued_at,updated_at=excluded.updated_at,
                 match_id=NULL""",
            (user_id, mode, level, rating, stamp, stamp),
        )

    await db.execute(
        """INSERT INTO matchmaking_rate_limits(user_id,last_joined_at) VALUES(?,?)
           ON CONFLICT(user_id) DO UPDATE SET last_joined_at=excluded.last_joined_at""",
        (user_id, stamp),
    )
    cursor = await db.execute(
        "SELECT user_id,mode,player_level,rating,status,queued_at,updated_at,match_id "
        "FROM matchmaking_queue WHERE user_id=?",
        (user_id,),
    )
    return await _queue_payload(db, await cursor.fetchone())


@_transactional
async def get_matchmaking_status(
    db: Any, user_id: int, *, now: int | None = None
) -> dict[str, Any] | None:
    if not _valid_id(user_id):
        raise MatchmakingError("Invalid player account.")
    stamp = _now(now)
    await db.execute(
        """UPDATE matchmaking_queue SET status='expired',updated_at=?
           WHERE user_id=? AND status='queued' AND queued_at<=?""",
        (stamp, user_id, stamp - MAX_QUEUE_WAIT_SECONDS),
    )
    cursor = await db.execute(
        "SELECT user_id,mode,player_level,rating,status,queued_at,updated_at,match_id "
        "FROM matchmaking_queue WHERE user_id=?",
        (user_id,),
    )
    row = await cursor.fetchone()
    return await _queue_payload(db, row) if row else None


@_transactional
async def cancel_matchmaking(db: Any, user_id: int, *, now: int | None = None) -> bool:
    if not _valid_id(user_id):
        raise MatchmakingError("Invalid player account.")
    stamp = _now(now)
    cursor = await db.execute(
        """UPDATE matchmaking_queue SET status='cancelled',updated_at=?
           WHERE user_id=? AND status='queued'""",
        (stamp, user_id),
    )
    return cursor.rowcount == 1


@_transactional
async def expire_matchmaking_queue(
    db: Any, *, now: int | None = None, max_wait: int = MAX_QUEUE_WAIT_SECONDS
) -> int:
    stamp = _now(now)
    if not isinstance(max_wait, int) or isinstance(max_wait, bool) or max_wait < 1:
        raise MatchmakingError("Invalid matchmaking expiry window.")
    cursor = await db.execute(
        """UPDATE matchmaking_queue SET status='expired',updated_at=?
           WHERE status='queued' AND queued_at<=?""",
        (stamp, stamp - max_wait),
    )
    return cursor.rowcount


@_transactional
async def complete_matchmaking_match(
    db: Any,
    match_id: int,
    winner_id: int | None = None,
    *,
    now: int | None = None,
) -> dict[str, Any]:
    if not _valid_id(match_id):
        raise MatchmakingError("Invalid matchmaking match.")
    if winner_id is not None and not _valid_id(winner_id):
        raise MatchmakingError("Invalid winning player.")
    stamp = _now(now)
    cursor = await db.execute(
        "SELECT player_one_id,player_two_id,status FROM matchmaking_matches WHERE match_id=?"
        + (" FOR UPDATE" if _is_postgres(db) else ""),
        (match_id,),
    )
    match = await cursor.fetchone()
    if not match:
        raise MatchmakingError("Match not found.")
    if match["status"] != "matched":
        raise MatchmakingError("This match is already closed.")
    if winner_id is not None and winner_id not in {
        match["player_one_id"],
        match["player_two_id"],
    }:
        raise MatchmakingError("The winner must be one of the matched players.")
    await db.execute(
        """UPDATE matchmaking_matches SET status='completed',completed_at=?,winner_id=?
           WHERE match_id=?""",
        (stamp, winner_id, match_id),
    )
    await db.execute(
        """UPDATE matchmaking_battles SET status='finished',winner_id=?,turn_user_id=NULL,
           turn_count=turn_count+1,updated_at=? WHERE match_id=? AND status='active'""",
        (winner_id, stamp, match_id),
    )
    await db.execute(
        """UPDATE matchmaking_queue SET status='completed',updated_at=?
           WHERE match_id=? AND status='matched'""",
        (stamp, match_id),
    )
    return {
        "match_id": match_id,
        "status": "completed",
        "winner_id": winner_id,
        "player_one_id": match["player_one_id"],
        "player_two_id": match["player_two_id"],
    }
