"""Abuse telemetry for suspicious game actions; never auto-bans players."""

MAX_SECURITY_EVENTS = 50_000
RETENTION_DAYS = 30
CLEANUP_INTERVAL = 250

EVENT_TYPES = {
    "invalid_battle_action",
    "invalid_monster_request",
    "invalid_social_action",
    "invalid_dungeon_action",
    "invalid_world_action",
    "invalid_story_action",
    "invalid_reward_claim",
    "invalid_premium_payment",
    "invalid_economy_action",
    "repeated_rate_limit",
}


class SecurityEventError(ValueError):
    pass

def classify_security_risk(event_count, risk_score, max_severity, economy_abuse_count, rate_limit_count):
    """Classify telemetry for human triage; this function never applies penalties."""
    values = (event_count, risk_score, max_severity, economy_abuse_count, rate_limit_count)
    if any(type(value) is not int or value < 0 for value in values):
        raise SecurityEventError("Security risk metrics must be non-negative integers.")
    if max_severity >= 5 or economy_abuse_count >= 4 or risk_score >= 15:
        return {"risk_level": "high", "recommended_action": "manual_review"}
    if max_severity >= 3 or economy_abuse_count >= 2 or rate_limit_count >= 3 or risk_score >= 8:
        return {"risk_level": "medium", "recommended_action": "monitor"}
    return {"risk_level": "low", "recommended_action": "log_only"}


def _is_postgres(db):
    return getattr(db, "dialect", "sqlite") == "postgres"


async def _begin_transaction(db, savepoint):
    nested = db.in_transaction
    if nested:
        await db.execute(f"SAVEPOINT {savepoint}")
    else:
        await db.execute("BEGIN IMMEDIATE")
    return nested


async def _finish_transaction(db, savepoint, nested):
    if nested:
        await db.execute(f"RELEASE SAVEPOINT {savepoint}")
    else:
        await db.commit()


async def _rollback_transaction(db, savepoint, nested):
    if nested:
        await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
        await db.execute(f"RELEASE SAVEPOINT {savepoint}")
    else:
        await db.rollback()


async def init_security_tables(db):
    savepoint = "init_security_tables"
    nested = await _begin_transaction(db, savepoint)
    try:
        if _is_postgres(db):
            await db.execute("""CREATE TABLE IF NOT EXISTS security_events(
              event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              user_id BIGINT NOT NULL,
              event_type TEXT NOT NULL,
              severity INTEGER NOT NULL DEFAULT 1 CHECK(severity BETWEEN 1 AND 5),
              details TEXT NOT NULL DEFAULT '',
              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )""")
        else:
            await db.execute("""CREATE TABLE IF NOT EXISTS security_events(
              event_id INTEGER PRIMARY KEY AUTOINCREMENT,
              user_id BIGINT NOT NULL,
              event_type TEXT NOT NULL,
              severity INTEGER NOT NULL DEFAULT 1 CHECK(severity BETWEEN 1 AND 5),
              details TEXT NOT NULL DEFAULT '',
              created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )""")
        await db.execute("CREATE INDEX IF NOT EXISTS idx_security_user_time ON security_events(user_id,created_at DESC)")
        await db.execute("CREATE INDEX IF NOT EXISTS idx_security_time ON security_events(created_at DESC)")
        await _finish_transaction(db, savepoint, nested)
    except Exception:
        await _rollback_transaction(db, savepoint, nested)
        raise


async def record_security_event(db, user_id, event_type, details="", severity=1):
    if not isinstance(user_id, int) or isinstance(user_id, bool) or user_id <= 0:
        raise SecurityEventError("Invalid player account.")
    if not isinstance(event_type, str) or event_type not in EVENT_TYPES:
        raise SecurityEventError("Unknown security event type.")
    if not isinstance(severity, int) or isinstance(severity, bool) or not 1 <= severity <= 5:
        raise SecurityEventError("Security severity must be between 1 and 5.")
    clean = " ".join(str(details or "").split())[:240]
    savepoint = "record_security_event"
    nested = await _begin_transaction(db, savepoint)
    try:
        insert_sql = (
            "INSERT INTO security_events(user_id,event_type,severity,details) "
            "VALUES(?,?,?,?) RETURNING event_id"
            if _is_postgres(db)
            else "INSERT INTO security_events(user_id,event_type,severity,details) VALUES(?,?,?,?)"
        )
        cur = await db.execute(insert_sql, (user_id, event_type, severity, clean))
        if _is_postgres(db):
            event_id = (await cur.fetchone())["event_id"]
        else:
            event_id = cur.lastrowid
        if int(event_id) % CLEANUP_INTERVAL == 0:
            if _is_postgres(db):
                await db.execute(
                    "DELETE FROM security_events WHERE created_at < CURRENT_TIMESTAMP - (? * INTERVAL '1 day')",
                    (RETENTION_DAYS,),
                )
            else:
                await db.execute(
                    "DELETE FROM security_events WHERE created_at < datetime('now', ?)",
                    (f"-{RETENTION_DAYS} days",),
                )
            await db.execute(
                """DELETE FROM security_events
                   WHERE event_id <= (
                     SELECT event_id FROM security_events
                     ORDER BY event_id DESC LIMIT 1 OFFSET ?
                   )""",
                (MAX_SECURITY_EVENTS,),
            )
        await _finish_transaction(db, savepoint, nested)
    except Exception:
        await _rollback_transaction(db, savepoint, nested)
        raise


async def get_suspicious_players(db, window_minutes=1440, limit=20):
    if not isinstance(window_minutes, int) or isinstance(window_minutes, bool) or not 1 <= window_minutes <= 10080:
        raise SecurityEventError("Security window must be between 1 and 10080 minutes.")
    if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= 50:
        raise SecurityEventError("Security result limit must be between 1 and 50.")
    cutoff = (
        "CURRENT_TIMESTAMP - (? * INTERVAL '1 minute')"
        if _is_postgres(db)
        else "datetime('now', ?)"
    )
    window = (window_minutes,) if _is_postgres(db) else (f"-{window_minutes} minutes",)
    cur = await db.execute(
        f"""SELECT user_id,COUNT(*) AS event_count,MAX(severity) AS max_severity,
                  SUM(severity) AS risk_score,
                  SUM(CASE WHEN severity >= 4 THEN 1 ELSE 0 END) AS high_severity_count,
                  COUNT(DISTINCT event_type) AS event_type_count,
                  SUM(CASE WHEN event_type='invalid_economy_action' THEN 1 ELSE 0 END) AS economy_abuse_count,
                  SUM(CASE WHEN event_type='repeated_rate_limit' THEN 1 ELSE 0 END) AS rate_limit_count,
                  MAX(created_at) AS last_seen
           FROM security_events
           WHERE created_at >= {cutoff}
           GROUP BY user_id
           ORDER BY risk_score DESC,high_severity_count DESC,event_count DESC,last_seen DESC
           LIMIT ?""",
        (*window, limit),
    )
    rows = await cur.fetchall()
    result = []
    for row in rows:
        item = dict(row)
        item.update(classify_security_risk(
            int(item["event_count"]), int(item["risk_score"]), int(item["max_severity"]),
            int(item["economy_abuse_count"]), int(item["rate_limit_count"]),
        ))
        result.append(item)
    return result


async def get_security_events(db, user_id, limit=20):
    if not isinstance(user_id, int) or isinstance(user_id, bool) or user_id <= 0:
        raise SecurityEventError("Invalid player account.")
    if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= 100:
        raise SecurityEventError("Security event limit must be between 1 and 100.")
    cur = await db.execute(
        """SELECT event_id,event_type,severity,details,created_at
           FROM security_events WHERE user_id=? ORDER BY event_id DESC LIMIT ?""",
        (user_id, limit),
    )
    return await cur.fetchall()
