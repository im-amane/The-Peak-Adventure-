"""Persistent party management for The Peak Adventure."""
from __future__ import annotations

import aiosqlite
import asyncio
from functools import wraps



_DB_WRITE_LOCKS: dict[tuple[int, int], asyncio.Lock] = {}


def _serialize_db_write(function):
    """Serialize writes and give each party operation an atomic boundary."""
    @wraps(function)
    async def wrapped(db, *args, **kwargs):
        key = (id(db), id(asyncio.get_running_loop()))
        lock = _DB_WRITE_LOCKS.get(key)
        if lock is None:
            lock = asyncio.Lock()
            _DB_WRITE_LOCKS[key] = lock
        async with lock:
            savepoint = "party_" + function.__name__
            nested = db.in_transaction
            if nested:
                await db.execute(f"SAVEPOINT {savepoint}")
            else:
                await db.execute("BEGIN IMMEDIATE")
            try:
                result = await function(db, *args, **kwargs)
                if nested:
                    await db.execute(f"RELEASE SAVEPOINT {savepoint}")
                else:
                    await db.commit()
                return result
            except Exception:
                if nested:
                    await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
                    await db.execute(f"RELEASE SAVEPOINT {savepoint}")
                else:
                    await db.rollback()
                raise
    return wrapped


def _is_postgres(db):
    return getattr(db, "dialect", "sqlite") == "postgres"


def _lock_party_sql(db):
    """Return the row-lock suffix needed to serialize party-wide limits on PostgreSQL."""
    return " FOR UPDATE" if _is_postgres(db) else ""


def _lock_player_sql(db):
    """Lock a player row while applying read-modify-write progression updates."""
    return " FOR UPDATE" if _is_postgres(db) else ""


def _is_integrity_error(exc):
    sqlstate = getattr(exc, "sqlstate", None)
    return isinstance(exc, aiosqlite.IntegrityError) or (
        isinstance(sqlstate, str) and sqlstate.startswith("23")
    )


MAX_PARTY_SIZE = 4


class PartyError(ValueError):
    """A party operation cannot be completed."""


def _valid_id(value: int) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


@_serialize_db_write
async def init_party_tables(db: aiosqlite.Connection) -> None:
    """Create party storage without committing a caller-owned transaction."""
    identity = (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if _is_postgres(db)
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    attack_timestamp_type = "TIMESTAMPTZ" if _is_postgres(db) else "TEXT"
    statements = (
        f"""CREATE TABLE IF NOT EXISTS parties (
          party_id {identity},
          leader_id BIGINT NOT NULL,
          created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS party_members (
          user_id BIGINT PRIMARY KEY,
          party_id BIGINT NOT NULL REFERENCES parties(party_id) ON DELETE CASCADE,
          joined_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        f"""CREATE TABLE IF NOT EXISTS party_invites (
          invite_id {identity},
          party_id BIGINT NOT NULL REFERENCES parties(party_id) ON DELETE CASCADE,
          inviter_id BIGINT NOT NULL,
          target_id BIGINT NOT NULL,
          status TEXT NOT NULL DEFAULT 'pending'
            CHECK(status IN ('pending','accepted','declined','cancelled')),
          created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
          responded_at TEXT
        )""",
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_party_pending_target ON party_invites(target_id) WHERE status='pending'",
        "CREATE INDEX IF NOT EXISTS idx_party_members_party ON party_members(party_id, joined_at)",
        f"""CREATE TABLE IF NOT EXISTS party_battles(
          battle_id {identity},party_id BIGINT NOT NULL,monster_level INTEGER NOT NULL,
          monster_name TEXT NOT NULL,max_hp INTEGER NOT NULL,hp INTEGER NOT NULL,
          status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','won')),
          created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS party_battle_contributions(
          battle_id BIGINT NOT NULL,user_id BIGINT NOT NULL,damage INTEGER NOT NULL DEFAULT 0,
          PRIMARY KEY(battle_id,user_id)
        )""",
        f"""CREATE TABLE IF NOT EXISTS party_battle_cooldowns(
          battle_id BIGINT NOT NULL,user_id BIGINT NOT NULL,last_attack_at {attack_timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP,
          PRIMARY KEY(battle_id,user_id)
        )""",
        """CREATE TABLE IF NOT EXISTS party_battle_rewards(
          battle_id BIGINT NOT NULL,user_id BIGINT NOT NULL,claimed_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
          PRIMARY KEY(battle_id,user_id)
        )""",
    )
    for statement in statements:
        await db.execute(statement)


@_serialize_db_write
async def create_party(db: aiosqlite.Connection, leader_id: int) -> int:
    if not _valid_id(leader_id):
        raise PartyError("Invalid player account.")
    cur = await db.execute("SELECT party_id FROM party_members WHERE user_id=?", (leader_id,))
    if await cur.fetchone():
        raise PartyError("You are already in a party. Leave it first.")
    insert_sql = (
        "INSERT INTO parties(leader_id) VALUES(?) RETURNING party_id"
        if _is_postgres(db)
        else "INSERT INTO parties(leader_id) VALUES(?)"
    )
    cur = await db.execute(insert_sql, (leader_id,))
    party_id = int((await cur.fetchone())["party_id"] if _is_postgres(db) else cur.lastrowid)
    await db.execute("INSERT INTO party_members(user_id,party_id) VALUES(?,?)", (leader_id, party_id))
    return party_id


@_serialize_db_write
async def invite_to_party(
    db: aiosqlite.Connection, party_id: int, inviter_id: int, target_id: int
) -> int:
    if not all(_valid_id(value) for value in (party_id, inviter_id, target_id)):
        raise PartyError("Invalid party or player account.")
    if inviter_id == target_id:
        raise PartyError("You cannot invite yourself.")
    cur = await db.execute(
        "SELECT leader_id FROM parties WHERE party_id=?" + _lock_party_sql(db),
        (party_id,),
    )
    party = await cur.fetchone()
    if not party:
        raise PartyError("Party not found.")
    if party["leader_id"] != inviter_id:
        raise PartyError("Only the party leader can invite players.")
    cur = await db.execute("SELECT 1 FROM party_members WHERE user_id=?", (target_id,))
    if await cur.fetchone():
        raise PartyError("That player is already in a party.")
    cur = await db.execute("SELECT COUNT(*) AS total FROM party_members WHERE party_id=?", (party_id,))
    if (await cur.fetchone())["total"] >= MAX_PARTY_SIZE:
        raise PartyError(f"Parties can have at most {MAX_PARTY_SIZE} players.")
    cur = await db.execute(
        "SELECT invite_id FROM party_invites WHERE target_id=? AND status='pending'",
        (target_id,),
    )
    if await cur.fetchone():
        raise PartyError("That player already has a pending party invitation.")
    insert_sql = (
        "INSERT INTO party_invites(party_id,inviter_id,target_id) VALUES(?,?,?) RETURNING invite_id"
        if _is_postgres(db)
        else "INSERT INTO party_invites(party_id,inviter_id,target_id) VALUES(?,?,?)"
    )
    try:
        cur = await db.execute(insert_sql, (party_id, inviter_id, target_id))
    except Exception as exc:
        if not _is_integrity_error(exc):
            raise
        raise PartyError("That player already has a pending party invitation.") from exc
    return int((await cur.fetchone())["invite_id"] if _is_postgres(db) else cur.lastrowid)


@_serialize_db_write
async def respond_to_party_invite(
    db: aiosqlite.Connection, invite_id: int, target_id: int, accept: bool
) -> None:
    if not _valid_id(invite_id) or not _valid_id(target_id) or type(accept) is not bool:
        raise PartyError("Invalid party invitation.")
    cur = await db.execute(
        "SELECT party_id,target_id,status FROM party_invites WHERE invite_id=?" + _lock_party_sql(db),
        (invite_id,),
    )
    invite = await cur.fetchone()
    if not invite or invite["status"] != "pending":
        raise PartyError("That party invitation is no longer active.")
    if invite["target_id"] != target_id:
        raise PartyError("Only the invited player can respond.")
    if accept:
        # Lock the parent party before checking capacity. Concurrent accepts on
        # separate PostgreSQL connections must observe each other serially.
        cur = await db.execute(
            "SELECT party_id FROM parties WHERE party_id=?" + _lock_party_sql(db),
            (invite["party_id"],),
        )
        if not await cur.fetchone():
            raise PartyError("Party not found.")
        cur = await db.execute("SELECT 1 FROM party_members WHERE user_id=?", (target_id,))
        if await cur.fetchone():
            raise PartyError("You are already in a party.")
        cur = await db.execute("SELECT COUNT(*) AS total FROM party_members WHERE party_id=?", (invite["party_id"],))
        if (await cur.fetchone())["total"] >= MAX_PARTY_SIZE:
            raise PartyError("That party is already full. The invitation remains pending until it is declined or space opens.")
        await db.execute(
            "INSERT INTO party_members(user_id,party_id) VALUES(?,?)",
            (target_id, invite["party_id"]),
        )
        status = "accepted"
    else:
        status = "declined"
    cur = await db.execute(
        "UPDATE party_invites SET status=?,responded_at=CURRENT_TIMESTAMP WHERE invite_id=? AND status='pending'",
        (status, invite_id),
    )
    if cur.rowcount != 1:
        raise PartyError("That party invitation was already handled.")



@_serialize_db_write
async def start_party_battle(db, party_id, user_id, monster_level, monster_name, monster_hp):
    if not _valid_id(party_id) or not _valid_id(user_id):
        raise PartyError("Invalid party or player account.")
    if not isinstance(monster_level, int) or isinstance(monster_level, bool) or not 1 <= monster_level <= 100:
        raise PartyError("Invalid co-op monster level.")
    if not isinstance(monster_hp, int) or isinstance(monster_hp, bool) or not 1 <= monster_hp <= 10_000_000:
        raise PartyError("Invalid co-op monster health.")
    clean_name = " ".join(str(monster_name or "").split())[:80]
    if not clean_name:
        raise PartyError("A monster name is required.")
    cur = await db.execute(
        "SELECT leader_id FROM parties WHERE party_id=?" + _lock_party_sql(db),
        (party_id,),
    )
    party = await cur.fetchone()
    if not party or party["leader_id"] != user_id:
        raise PartyError("Only the party leader can start a co-op battle.")
    cur = await db.execute("SELECT 1 FROM party_battles WHERE party_id=? AND status='active'", (party_id,))
    if await cur.fetchone():
        raise PartyError("Your party already has an active co-op battle.")
    insert_sql = (
        "INSERT INTO party_battles(party_id,monster_level,monster_name,max_hp,hp) VALUES(?,?,?,?,?) RETURNING battle_id"
        if _is_postgres(db)
        else "INSERT INTO party_battles(party_id,monster_level,monster_name,max_hp,hp) VALUES(?,?,?,?,?)"
    )
    cur = await db.execute(
        insert_sql, (party_id, monster_level, clean_name, monster_hp, monster_hp)
    )
    return int((await cur.fetchone())["battle_id"] if _is_postgres(db) else cur.lastrowid)

@_serialize_db_write
async def attack_party_battle(db, party_id, user_id, damage):
    if not _valid_id(party_id) or not _valid_id(user_id):
        raise PartyError("Invalid party or player account.")
    if not isinstance(damage, int) or isinstance(damage, bool) or not 1 <= damage <= 10000:
        raise PartyError("Invalid co-op attack damage.")
    cur = await db.execute(
        "SELECT 1 FROM party_members WHERE party_id=? AND user_id=?",
        (party_id, user_id),
    )
    if not await cur.fetchone():
        raise PartyError("Only party members can attack this monster.")
    cur = await db.execute(
        "SELECT * FROM party_battles WHERE party_id=? AND status='active' ORDER BY battle_id DESC LIMIT 1",
        (party_id,),
    )
    battle = await cur.fetchone()
    if not battle:
        raise PartyError("There is no active co-op battle.")
    cooldown_sql = (
        """SELECT 1 FROM party_battle_cooldowns
           WHERE battle_id=? AND user_id=?
           AND CURRENT_TIMESTAMP-last_attack_at<INTERVAL '5 seconds'"""
        if _is_postgres(db)
        else """SELECT 1 FROM party_battle_cooldowns
           WHERE battle_id=? AND user_id=?
           AND julianday(CURRENT_TIMESTAMP)-julianday(last_attack_at)<(5.0/86400)"""
    )
    cur = await db.execute(cooldown_sql, (battle["battle_id"], user_id))
    if await cur.fetchone():
        raise PartyError("Co-op attack cooldown: wait 5 seconds.")
    hp = max(0, battle["hp"] - damage)
    dealt = battle["hp"] - hp
    status = "won" if hp == 0 else "active"
    cur = await db.execute(
        "UPDATE party_battles SET hp=?,status=? WHERE battle_id=? AND status='active' AND hp=?",
        (hp, status, battle["battle_id"], battle["hp"]),
    )
    if cur.rowcount != 1:
        raise PartyError("The co-op battle changed; retry your attack.")
    await db.execute(
        """INSERT INTO party_battle_cooldowns(battle_id,user_id,last_attack_at)
           VALUES(?,?,CURRENT_TIMESTAMP)
           ON CONFLICT(battle_id,user_id) DO UPDATE SET last_attack_at=CURRENT_TIMESTAMP""",
        (battle["battle_id"], user_id),
    )
    damage_expression = (
        "party_battle_contributions.damage+excluded.damage"
        if _is_postgres(db)
        else "damage+excluded.damage"
    )
    await db.execute(
        f"""INSERT INTO party_battle_contributions(battle_id,user_id,damage) VALUES(?,?,?)
           ON CONFLICT(battle_id,user_id) DO UPDATE SET damage={damage_expression}""",
        (battle["battle_id"], user_id, dealt),
    )
    cur = await db.execute(
        "SELECT user_id FROM party_members WHERE party_id=? ORDER BY joined_at",
        (party_id,),
    )
    members = [row["user_id"] for row in await cur.fetchall()]
    return {
        "battle_id": battle["battle_id"], "monster_name": battle["monster_name"],
        "hp": hp, "max_hp": battle["max_hp"], "damage": dealt,
        "status": status, "members": members,
    }

