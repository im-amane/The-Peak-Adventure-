"""Small in-memory sliding-window limiter for authenticated game API traffic."""
from __future__ import annotations

import time
import math
import asyncio
import weakref
from collections import deque


_CONNECTION_LOCKS = weakref.WeakKeyDictionary()


def _connection_lock(db):
    """Return one async lock shared by all limiter instances using this connection."""
    lock = _CONNECTION_LOCKS.get(db)
    if lock is None:
        lock = asyncio.Lock()
        _CONNECTION_LOCKS[db] = lock
    return lock


class SlidingWindowRateLimiter:
    """Track request timestamps per key without trusting client-supplied IP headers."""

    def __init__(self, window_seconds: int = 60, max_keys: int = 10000):
        if (
            not isinstance(window_seconds, int) or isinstance(window_seconds, bool) or window_seconds < 1
            or not isinstance(max_keys, int) or isinstance(max_keys, bool) or max_keys < 1
        ):
            raise ValueError("window_seconds and max_keys must be positive integers")
        self.window_seconds = window_seconds
        self.max_keys = max_keys
        self._events: dict[str, deque[float]] = {}

    def allow(self, key: str, limit: int, now: float | None = None) -> tuple[bool, int]:
        """Return (allowed, retry_after_seconds); limit is per key and window."""
        if not isinstance(key, str) or not key.strip():
            raise ValueError("key must be a non-empty string")
        if not isinstance(limit, int) or isinstance(limit, bool) or limit < 1:
            raise ValueError("limit must be a positive integer")
        current = time.monotonic() if now is None else now
        if isinstance(current, bool) or not isinstance(current, (int, float)) or not math.isfinite(current):
            raise ValueError("now must be a finite monotonic timestamp")
        events = self._events.setdefault(key, deque())
        cutoff = current - self.window_seconds
        while events and events[0] <= cutoff:
            events.popleft()
        if len(events) >= limit:
            return False, max(1, int(self.window_seconds - (current - events[0])) + 1)
        events.append(current)
        if len(self._events) > self.max_keys:
            stale = [entry for entry, timestamps in self._events.items()
                     if not timestamps or timestamps[-1] <= cutoff]
            for entry in stale:
                self._events.pop(entry, None)
            while len(self._events) > self.max_keys:
                oldest = min(
                    self._events,
                    key=lambda entry: self._events[entry][-1] if self._events[entry] else float("-inf"),
                )
                self._events.pop(oldest, None)
        return True, 0


class DatabaseSlidingWindowRateLimiter:
    """Share sliding-window limits across processes using the application's database.

    PostgreSQL requests serialize by advisory lock per key. SQLite uses its
    write transaction lock. The in-memory limiter remains useful as a fallback
    when the database is not initialized.
    """

    def __init__(self, window_seconds: int = 60, cleanup_every: int = 100):
        if (
            not isinstance(window_seconds, int) or isinstance(window_seconds, bool) or window_seconds < 1
            or not isinstance(cleanup_every, int) or isinstance(cleanup_every, bool) or cleanup_every < 1
        ):
            raise ValueError("window_seconds and cleanup_every must be positive integers")
        self.window_seconds = window_seconds
        self.cleanup_every = cleanup_every
        self._operations = 0

    async def init(self, db) -> None:
        async with _connection_lock(db):
            await self._init_locked(db)

    async def _init_locked(self, db) -> None:
        nested = db.in_transaction
        savepoint = "init_api_rate_limit_tables"
        if nested:
            await db.execute(f"SAVEPOINT {savepoint}")
        else:
            await db.execute("BEGIN IMMEDIATE")
        identity = (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            if getattr(db, "dialect", "sqlite") == "postgres"
            else "INTEGER PRIMARY KEY AUTOINCREMENT"
        )
        try:
            await db.execute(
                f"""CREATE TABLE IF NOT EXISTS api_rate_limit_events(
                    event_id {identity},
                    rate_key TEXT NOT NULL,
                    occurred_at DOUBLE PRECISION NOT NULL
                )"""
            )
            await db.execute(
                "CREATE INDEX IF NOT EXISTS idx_api_rate_limit_key_time "
                "ON api_rate_limit_events(rate_key, occurred_at)"
            )
            await db.execute(
                "CREATE INDEX IF NOT EXISTS idx_api_rate_limit_event_time "
                "ON api_rate_limit_events(occurred_at)"
            )
            if nested:
                await db.execute(f"RELEASE SAVEPOINT {savepoint}")
            else:
                await db.commit()
        except Exception:
            if nested:
                await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
                await db.execute(f"RELEASE SAVEPOINT {savepoint}")
            else:
                await db.rollback()
            raise

    async def allow(self, db, key: str, limit: int, now: float | None = None) -> tuple[bool, int]:
        if not isinstance(key, str) or not key.strip():
            raise ValueError("key must be a non-empty string")
        if not isinstance(limit, int) or isinstance(limit, bool) or limit < 1:
            raise ValueError("limit must be a positive integer")
        current = time.time() if now is None else now
        if isinstance(current, bool) or not isinstance(current, (int, float)) or not math.isfinite(current):
            raise ValueError("now must be a finite timestamp")

        async with _connection_lock(db):
            return await self._allow_locked(db, key, limit, current)

    async def _allow_locked(
        self, db, key: str, limit: int, current: float
    ) -> tuple[bool, int]:
        nested = db.in_transaction
        savepoint = "api_rate_limit_check"
        if nested:
            await db.execute(f"SAVEPOINT {savepoint}")
        else:
            await db.execute("BEGIN IMMEDIATE")
        try:
            if getattr(db, "dialect", "sqlite") == "postgres":
                await db.execute(
                    "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
                    (key,),
                )
            cutoff = current - self.window_seconds
            await db.execute(
                "DELETE FROM api_rate_limit_events WHERE rate_key=? AND occurred_at<=?",
                (key, cutoff),
            )
            self._operations += 1
            if self._operations % self.cleanup_every == 0:
                await db.execute(
                    "DELETE FROM api_rate_limit_events WHERE occurred_at<=?",
                    (cutoff,),
                )
            cur = await db.execute(
                "SELECT COUNT(*) AS total, MIN(occurred_at) AS oldest "
                "FROM api_rate_limit_events WHERE rate_key=?",
                (key,),
            )
            row = await cur.fetchone()
            total = row["total"]
            if total >= limit:
                retry_after = max(1, math.ceil(self.window_seconds - (current - row["oldest"])))
                allowed = False
            else:
                await db.execute(
                    "INSERT INTO api_rate_limit_events(rate_key,occurred_at) VALUES(?,?)",
                    (key, current),
                )
                allowed, retry_after = True, 0

            if nested:
                await db.execute(f"RELEASE SAVEPOINT {savepoint}")
            else:
                await db.commit()
            return allowed, retry_after
        except Exception:
            if nested:
                await db.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
                await db.execute(f"RELEASE SAVEPOINT {savepoint}")
            else:
                await db.rollback()
            raise
